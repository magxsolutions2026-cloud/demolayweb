-- Supabase (PostgreSQL) schema for demolayweb.
-- Consolidates the legacy MySQL db-init.sql plus every db-migration-*.sql into one script.
-- Run once in the Supabase SQL Editor (or: psql "$DATABASE_URL" -f db-init.sql).
-- The old db-migration-*.sql / db-seed*.sql files are MySQL-era references and are superseded by this file.

-- Postgres equivalent of MySQL's "ON UPDATE CURRENT_TIMESTAMP" for updated_at columns.
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE IF NOT EXISTS admins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(100) NOT NULL UNIQUE,
  name VARCHAR(160) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(64) NOT NULL DEFAULT 'Super Admin',
  status VARCHAR(16) NOT NULL DEFAULT 'Active',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);



CREATE TABLE IF NOT EXISTS events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  event_date DATE NOT NULL,
  event_time VARCHAR(64) NOT NULL,
  location VARCHAR(255) NOT NULL,
  description TEXT,
  category VARCHAR(32) NOT NULL DEFAULT 'activity',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS officers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  position VARCHAR(255) NOT NULL,
  photo_url VARCHAR(512),
  photo_pos_x SMALLINT NOT NULL DEFAULT 50,   -- 0-100 horizontal focal
  photo_pos_y SMALLINT NOT NULL DEFAULT 45,   -- 0-100 vertical focal
  photo_zoom SMALLINT NOT NULL DEFAULT 100,   -- 100=cover, up to 200=tighter zoom
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS petitioners (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  age INTEGER,
  email VARCHAR(255) NOT NULL,
  phone VARCHAR(50),
  address TEXT,
  school VARCHAR(255),
  reason TEXT,
  status VARCHAR(16) NOT NULL DEFAULT 'Pending'
    CHECK (status IN ('Pending', 'Approved', 'Declined')),
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS subscribers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  date_subscribed TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS landing_content (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section VARCHAR(100) NOT NULL UNIQUE,
  content JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS gallery (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  image_url VARCHAR(512) NOT NULL,
  caption TEXT,
  is_published SMALLINT NOT NULL DEFAULT 1,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS news (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  slug VARCHAR(255) NOT NULL UNIQUE,
  summary TEXT,
  content TEXT,
  image_urls JSONB,
  is_published SMALLINT NOT NULL DEFAULT 1,
  published_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  newsletter_sent_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS campaigns (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  slug VARCHAR(255) UNIQUE,
  goal_amount DECIMAL(12,2) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'active'
    CHECK (status IN ('draft', 'active', 'completed')),
  campaign_type VARCHAR(16) NOT NULL DEFAULT 'general'
    CHECK (campaign_type IN ('general', 'tshirt')),
  summary TEXT,
  description TEXT,
  cover_image_url VARCHAR(512),
  image_urls JSONB,
  unit_price DECIMAL(12,2),
  size_options TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS campaign_orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id INTEGER NOT NULL,
  brother_name VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL,
  phone VARCHAR(64),
  shirt_size VARCHAR(32) NOT NULL,
  quantity INTEGER NOT NULL DEFAULT 1,
  unit_price DECIMAL(12,2) NOT NULL,
  total_amount DECIMAL(12,2) NOT NULL,
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_campaign_orders_campaign
    FOREIGN KEY (campaign_id) REFERENCES campaigns(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS fund_sources (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  source_type VARCHAR(32) NOT NULL DEFAULT 'donations'
    CHECK (source_type IN ('donations', 'events', 'contributions', 'sponsors', 'other')),
  source_specify VARCHAR(255),
  source_date DATE NOT NULL,
  description TEXT,
  campaign_id INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_fund_sources_campaign
    FOREIGN KEY (campaign_id) REFERENCES campaigns(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS disbursements (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  category VARCHAR(64) NOT NULL,
  disbursement_date DATE NOT NULL,
  purpose TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS fund_activity (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action_type VARCHAR(32) NOT NULL,
  message VARCHAR(512) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Indexes (from db-migration-funds.sql / db-migration-tshirt-campaign-orders.sql)
CREATE INDEX IF NOT EXISTS idx_campaign_orders_campaign ON campaign_orders (campaign_id, created_at);
CREATE INDEX IF NOT EXISTS idx_campaign_orders_email ON campaign_orders (email);
CREATE INDEX IF NOT EXISTS idx_fund_sources_date ON fund_sources (source_date);
CREATE INDEX IF NOT EXISTS idx_fund_sources_campaign ON fund_sources (campaign_id);
CREATE INDEX IF NOT EXISTS idx_disbursements_date ON disbursements (disbursement_date);
CREATE INDEX IF NOT EXISTS idx_disbursements_category ON disbursements (category);
CREATE INDEX IF NOT EXISTS idx_fund_activity_created ON fund_activity (created_at);

-- updated_at auto-touch triggers
DROP TRIGGER IF EXISTS trg_admins_updated_at ON admins;
CREATE TRIGGER trg_admins_updated_at BEFORE UPDATE ON admins
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_landing_content_updated_at ON landing_content;
CREATE TRIGGER trg_landing_content_updated_at BEFORE UPDATE ON landing_content
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_news_updated_at ON news;
CREATE TRIGGER trg_news_updated_at BEFORE UPDATE ON news
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_campaigns_updated_at ON campaigns;
CREATE TRIGGER trg_campaigns_updated_at BEFORE UPDATE ON campaigns
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_fund_sources_updated_at ON fund_sources;
CREATE TRIGGER trg_fund_sources_updated_at BEFORE UPDATE ON fund_sources
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_disbursements_updated_at ON disbursements;
CREATE TRIGGER trg_disbursements_updated_at BEFORE UPDATE ON disbursements
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

